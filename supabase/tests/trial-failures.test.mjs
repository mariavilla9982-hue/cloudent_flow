import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
import vm from 'node:vm';
const source=readFileSync(new URL('../functions/cloudent-trial-worker/index.ts',import.meta.url),'utf8');
new vm.Script(stripTypeScriptTypes(source.replace(/^import .*;\s*$/gm,''),{mode:'transform'}));
const helper=source.slice(source.indexOf('function trialFailureReason'),source.indexOf('type InstagramRoute'));
const classify=new Function(stripTypeScriptTypes(helper)+';return trialFailureReason')();
assert.equal(classify(Object.assign(new Error('Authorization failed'),{payload:{code:190}})),'instagram_reconnect_required');
assert.equal(classify(new Error('Error validating access token: The session has been invalidated')),'instagram_reconnect_required');
assert.equal(classify(new Error('A conta do Instagram não atende ao requisito de seguidores para reels de teste para criar reels de teste.')),'trial_not_eligible');
assert.equal(classify(new Error('Meta API 503')),null);
assert.equal(classify(new Error('Video is still processing')),null);
const html=readFileSync(new URL('../../index.html',import.meta.url),'utf8');
const badge=html.slice(html.indexOf('function calendarPretrialBadge'),html.indexOf('function renderSlot'));
const render=new Function('esc',badge+';return calendarPretrialBadge')(s=>String(s).replaceAll('"','&quot;'));
assert.match(render({pretrial:{status:'failed',meta:{failure_reason:'instagram_reconnect_required'}}}),/Reconectar Instagram/);
assert.match(render({pretrial:{status:'failed',meta:{failure_reason:'trial_not_eligible'}}}),/Trial indisponível/);
assert.match(render({pretrial:{status:'failed',last_error:'Reel normal já publicado; Pré-Trial pendente encerrado.'}}),/Trial encerrado/);
assert.match(render({pretrial:{status:'failed',last_error:'Unknown error'}}),/Trial erro/);
assert.match(render({pretrial:{status:'published',meta:{failure_reason:'trial_not_eligible'}}}),/Trial ✓/);
console.log('Permanent Trial failures, transient retries, clear badges and published precedence: passed.');
